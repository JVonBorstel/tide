# Owns kitchen/MAP.md: every .ps1/.mjs/.js under kitchen/, scripts/ and pass-app/ with its line count, header line and functions.
# Called by hand (and by any PR that adds, removes or renames code) so agents read the map, not the files. No AI, no dates: same code, same map.
#   pwsh -File scripts/make-map.ps1 [-Root <repo>] [-Out <file>]
# Not the same file as <worktree>\.kitchen\MAP.md, which kitchen/stations/map.ps1 writes per order and never commits.
param([string]$Root = '', [string]$Out = '')
$ErrorActionPreference = 'Stop'
if (-not $Root) { $Root = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path }
if (-not (Test-Path -LiteralPath $Root)) { Write-Output "make-map: folder not found: $Root"; exit 2 }
if (-not $Out) { $Out = Join-Path $Root 'kitchen\MAP.md' }
. (Join-Path $PSScriptRoot 'standards-lib.ps1')
try { $files = Get-StdFiles $Root @('kitchen', 'scripts', 'pass-app') } catch { Write-Output "make-map: $($_.Exception.Message)"; exit 2 }

$sb = [Text.StringBuilder]::new()
[void]$sb.AppendLine('# Code map of brain-monitor (generated by scripts/make-map.ps1; do not edit by hand, re-run it)')
[void]$sb.AppendLine('Each entry: file (lines) - its header (what it owns; who calls it), or "no header". Then its functions. Rules: kitchen/STANDARDS.md.')
$total = 0
foreach ($grp in ($files | Group-Object { $p = $_ -split '/'; if ($p.Count -gt 2) { "$($p[0])/$($p[1])" } else { $p[0] } } | Sort-Object Name)) {
    [void]$sb.AppendLine(''); [void]$sb.AppendLine("## $($grp.Name)/")
    foreach ($rel in $grp.Group) {
        $p = Join-Path $Root $rel; $lines = Get-StdLines $p; $total += $lines.Count
        $h = Get-StdHeader $p $lines
        $say = if ($h) { "$($h[0]); $($h[1])" } else { 'no header' }
        if ($say.Length -gt 240) { $say = $say.Substring(0, 237) + '...' }
        [void]$sb.AppendLine("- ``$rel`` ($($lines.Count)) - $say")
        $fn = @(Get-StdFunctions $p)
        if ($fn.Count) { [void]$sb.AppendLine("  functions: $($fn -join ', ')") }
    }
}
[void]$sb.AppendLine(''); [void]$sb.AppendLine("$($files.Count) files, $total lines.")
$dir = Split-Path -Parent $Out; if ($dir -and -not (Test-Path -LiteralPath $dir)) { New-Item -ItemType Directory -Force -Path $dir | Out-Null }
[IO.File]::WriteAllText($Out, $sb.ToString().Replace("`r`n", "`n"), [Text.UTF8Encoding]::new($false))
Write-Output "make-map: $($files.Count) files, $total lines -> $Out"
